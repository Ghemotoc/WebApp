/**
 * Splits the demo content top-up into parts the Supabase SQL Editor accepts (Lane B, CTO,
 * 24 Oct 2026: the 2.6 MB single file was refused with "Query is too large to be run via the SQL
 * Editor").
 *
 * How it splits: never by searching the text. The generator (scripts/build-demo-content.ts)
 * hands over the statements it made, in order: the settings and the accounts, then each story's
 * row and tags followed by its chapters, one statement each. This file packs them, in that same
 * order, into parts under the size limit, so a chapter always comes after its story's row (in
 * the same part or a later one) and every row a foreign key points to already exists.
 * What each part holds: its own begin; and commit;, the personas guard (step 1) at the top, and
 * idempotent statements only, so each part is safe to run twice. Part 01 also holds the settings
 * and the accounts; the last part ends with the check query.
 * Who calls it: scripts/build-demo-content.ts (npm run demo:build), which writes the parts to
 * supabase/staging-topups/demo-content-2a/part-NN.sql next to the single file.
 * Tests: scripts/demo-content-parts.test.ts; scripts/compare-demo-parts.ts (npm run
 * demo:compare-parts) runs both on a fresh local database and compares the rows.
 */
import { mkdirSync, readdirSync, rmSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/**
 * The most one part may hold, in bytes. The SQL Editor's own limit is not published; the CTO's
 * ceiling is 500 KB, and 450,000 bytes keeps every part clearly under it however a kilobyte is
 * counted (500,000 or 512,000 bytes).
 */
export const maximumPartBytes = 450_000;

/** What the generator hands over: the fixed pieces and the statements, in run order. */
export interface TopUpPieces {
  /** Step 1: refuse a database without the seed personas. Repeated at the top of every part. */
  guard: string;
  /** The settings and the accounts. Part 01 only: every story points at one of the accounts. */
  opening: string;
  /** Every story row (with its tags) and every chapter, one statement each, in run order. */
  statements: string[];
  /** The check the run ends with. Last part only. */
  checkQuery: string;
}

/**
 * The comment at the top of one part.
 *
 * @param partNumber - from 1
 * @param partCount - how many parts there are
 * @returns the header, ending with a newline
 */
export function partHeader(partNumber: number, partCount: number): string {
  return `-- Staging top-up: demo content, part 2a, file ${partNumber} of ${partCount}. GENERATED by npm run demo:build:
-- edit content/demo-stories/ and content/classics/texts/, never this file.
-- In the SQL Editor, run the parts in order, 01 first; each is its own transaction and safe to run twice.
-- The same top-up as one file, for psql: supabase/staging-topups/demo-content-2a.sql.
`;
}

/**
 * Wraps one part's statements: header, begin;, the guard, (part 01) the opening, the statements,
 * commit; and (last part) the check query.
 *
 * @param body - the statements, joined
 * @param partNumber - from 1
 * @param partCount - how many parts there are
 * @param pieces - the guard, opening and check query
 * @returns the part's SQL
 */
function wrapPart(
  body: string,
  partNumber: number,
  partCount: number,
  pieces: TopUpPieces,
): string {
  const opening = partNumber === 1 ? `${pieces.opening}\n` : '';
  const check = partNumber === partCount ? `\n${pieces.checkQuery}` : '';
  return `${partHeader(partNumber, partCount)}begin;\n\n${pieces.guard}\n${opening}${body}commit;\n${check}`;
}

/**
 * Packs the statements into as few parts as fit, each under the limit once wrapped.
 *
 * @param pieces - from the generator
 * @param limitBytes - the most one part may hold, in UTF-8 bytes (the SQL Editor counts bytes)
 * @returns each part's SQL, in run order
 * Errors: throws when one statement alone can't fit in a part.
 */
export function splitIntoParts(pieces: TopUpPieces, limitBytes = maximumPartBytes): string[] {
  // Room every part must keep for its wrapping: the header (with a two-digit count), begin;, the
  // guard, commit; and the check query (any part may turn out to be the last).
  const wrapping =
    Buffer.byteLength(wrapPart('', 99, 99, pieces)) + Buffer.byteLength(pieces.checkQuery) + 2;
  const bodies: string[][] = [[]];
  let usedBytes = Buffer.byteLength(pieces.opening) + 1;

  for (const statement of pieces.statements) {
    const statementBytes = Buffer.byteLength(statement);
    if (wrapping + statementBytes > limitBytes) {
      throw new Error(`one statement is ${statementBytes} bytes, too big for a part`);
    }
    // Start a new part when this statement would push the current one over the limit.
    if (wrapping + usedBytes + statementBytes > limitBytes) {
      bodies.push([]);
      usedBytes = 0;
    }
    bodies[bodies.length - 1]?.push(statement);
    usedBytes += statementBytes;
  }

  return bodies.map((body, index) => wrapPart(body.join(''), index + 1, bodies.length, pieces));
}

/**
 * Writes the parts as part-01.sql, part-02.sql and so on, removing any part file a previous
 * build left (so a shorter top-up never leaves a stale part behind).
 *
 * @param folder - supabase/staging-topups/demo-content-2a
 * @param parts - from splitIntoParts()
 */
export function writeParts(folder: string, parts: string[]): void {
  mkdirSync(folder, { recursive: true });
  for (const fileName of readdirSync(folder).filter((name) => /^part-\d+\.sql$/.test(name))) {
    rmSync(join(folder, fileName));
  }
  parts.forEach((part, index) => {
    writeFileSync(join(folder, `part-${String(index + 1).padStart(2, '0')}.sql`), part);
  });
}
