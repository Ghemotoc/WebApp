/**
 * Unit tests for the safety contacts migration builder (story S1-E10-13a): the SQL it writes holds
 * exactly what content/safety-contacts.json holds, nothing typed from memory.
 */
import { readFileSync } from 'node:fs';
import { resolve } from 'node:path';

import { describe, expect, it } from 'vitest';

import { migrationFromRows, rowsFromJson, sqlText } from './build-safety-contacts-migration';

const json = JSON.parse(readFileSync(resolve('content/safety-contacts.json'), 'utf8')) as Record<
  string,
  Record<string, unknown>
>;

describe('rowsFromJson', () => {
  it('keeps every country in the file, Romania included, with its check date', () => {
    const rows = rowsFromJson(json);
    expect(new Set(rows.map((row) => row.countryCode))).toEqual(new Set(Object.keys(json)));
    expect(rows.find((row) => row.countryCode === 'RO')?.lastCheckedOn).toBe('2026-10-17');
  });

  it('keeps Romania’s 112, Telefonul Copilului and Ora de Net exactly as the research has them', () => {
    const romania = rowsFromJson(json).filter((row) => row.countryCode === 'RO');
    expect(romania.find((row) => row.kind === 'emergency')?.phoneNumber).toBe('112');
    const helpline = romania.find((row) => row.kind === 'child_helpline');
    expect(helpline?.phoneNumber).toBe('116 111');
    expect(helpline?.link).toBe('https://www.telefonulcopilului.ro');
    expect(romania.find((row) => row.kind === 'csam_hotline')?.link).toBe(
      'https://oradenet.ro/esc-abuz',
    );
  });

  it('leaves out adult-only lines (no ARPS line for Romania, decided 23 Oct 2026) and the unconfirmed lists', () => {
    const rows = rowsFromJson(json);
    expect(rows.some((row) => /adult-focused/i.test(row.label))).toBe(false);
    expect(rows.some((row) => (row.kind as string) === 'unconfirmed')).toBe(false);
  });

  it('numbers the lines of a kind from 1 in the file’s order', () => {
    const britishEmergency = rowsFromJson(json).filter(
      (row) => row.countryCode === 'GB' && row.kind === 'emergency',
    );
    expect(britishEmergency.map((row) => row.position)).toEqual([1, 2, 3, 4]);
  });
});

describe('sqlText and migrationFromRows', () => {
  it('quotes text and doubles single quotes', () => {
    expect(sqlText("Children's line")).toBe("'Children''s line'");
    expect(sqlText(null)).toBe('null');
  });

  it('writes one insert with one line per row and the generated-file warning', () => {
    const sql = migrationFromRows(rowsFromJson(json).slice(0, 2));
    expect(sql).toContain('GENERATED by scripts/build-safety-contacts-migration.ts');
    expect(sql).toContain("delete from public.safety_contacts where checked_by = 'research G4';");
    expect(sql).toContain('insert into public.safety_contacts');
    expect(sql.trim().endsWith(');')).toBe(true);
    expect(sql).toContain("('RO', 'emergency', 1, 'Număr unic de urgență 112', '112',");
  });
});
