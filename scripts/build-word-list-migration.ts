/**
 * Turns the swearword lists in content/username-word-lists/ into a migration that replaces
 * public.username_word_lists (story S1-E2-04).
 *
 * Who runs it: a person, by hand, after changing a list (for example after Robert checks the
 * Romanian one). Every change becomes its own migration. Example (one line):
 *   npx tsx scripts/build-word-list-migration.ts
 *     --output supabase/migrations/<time>_s1_e2_04_username_word_lists.sql
 * What it reads: content/username-word-lists/<language>.txt, one word per line; "#" starts a
 *   comment; "=word" means "only as a whole word" (see the files' headers).
 * What it writes: one SQL file that empties the table and inserts every word. The database folds
 *   each word itself (trigger fold_listed_name), so the file holds the words as written.
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { parseArgs } from 'node:util';

/** One entry of a list. */
export interface ListedWord {
  language: string;
  word: string;
  matchRule: 'anywhere' | 'whole_word';
}

/** The languages the table accepts (username_word_lists_language_is_known). */
const knownLanguages = ['en', 'ro'];

/**
 * Reads one list file.
 *
 * @param fileText - the file's contents
 * @param language - 'en' or 'ro', from the file name
 * @returns one entry per word, in file order
 * Errors: throws for a word with a quote or a space, which would be a typing mistake.
 */
export function parseWordList(fileText: string, language: string): ListedWord[] {
  const words: ListedWord[] = [];
  for (const rawLine of fileText.split(/\r?\n/)) {
    // Drop comments and blank lines.
    const line = rawLine.split('#')[0]?.trim() ?? '';
    if (line === '') continue;
    // "=" at the start means "only as a whole word".
    const isWholeWord = line.startsWith('=');
    const word = (isWholeWord ? line.slice(1) : line).trim().toLowerCase();
    if (/['\s]/.test(word)) throw new Error(`"${word}" in ${language}.txt has a quote or a space.`);
    words.push({ language, word, matchRule: isWholeWord ? 'whole_word' : 'anywhere' });
  }
  return words;
}

/**
 * Builds the migration's SQL.
 *
 * @param words - every entry of every list
 * @returns the SQL file's text
 * Errors: throws when a word appears twice in one language.
 */
export function buildWordListMigration(words: ListedWord[]): string {
  // Step 1: refuse duplicates, which would break the table's unique key half-way through.
  const seen = new Set<string>();
  for (const entry of words) {
    const key = `${entry.language}:${entry.word}`;
    if (seen.has(key)) throw new Error(`"${entry.word}" appears twice in ${entry.language}.txt.`);
    seen.add(key);
  }
  // Step 2: one row per word.
  const rows = words.map(
    (entry) => `  ('${entry.language}', '${entry.word}', '${entry.matchRule}')`,
  );
  return [
    '-- The username and pen name swearword lists (story S1-E2-04).',
    '-- Generated by scripts/build-word-list-migration.ts from content/username-word-lists/.',
    '-- Do not edit by hand: change the lists and generate a new migration. Drafts: Robert checks',
    '-- the Romanian list before release (decided 17 Oct 2026, 19:43, Q4).',
    '',
    'delete from public.username_word_lists;',
    '',
    'insert into public.username_word_lists (language, word, match_rule) values',
    `${rows.join(',\n')};`,
    '',
  ].join('\n');
}

/**
 * Reads every list in a folder.
 *
 * @param folder - the content/username-word-lists folder
 * @returns all entries, English first
 * Errors: throws for a file whose name isn't a known language.
 */
export function readWordLists(folder: string): ListedWord[] {
  const fileNames = readdirSync(folder)
    .filter((fileName) => fileName.endsWith('.txt'))
    .sort();
  return fileNames.flatMap((fileName) => {
    const language = fileName.replace(/\.txt$/, '');
    if (!knownLanguages.includes(language)) throw new Error(`Unknown language file ${fileName}.`);
    return parseWordList(readFileSync(`${folder}/${fileName}`, 'utf8'), language);
  });
}

/** Reads the command line, builds the migration and writes it. */
function main(): void {
  const { values } = parseArgs({ options: { output: { type: 'string' } } });
  if (!values.output) throw new Error('Give --output (see the header).');
  const folder = fileURLToPath(new URL('../content/username-word-lists', import.meta.url));
  const words = readWordLists(folder);
  writeFileSync(values.output, buildWordListMigration(words));
  console.log(`Wrote ${String(words.length)} words to ${values.output}.`);
}

// Run main() only when this file is started directly, not when a test imports it.
if (process.argv[1] !== undefined && import.meta.url === pathToFileURL(process.argv[1]).href) {
  main();
}
