/**
 * Builds the migration that seeds safety_contacts from content/safety-contacts.json (story
 * S1-E10-13a; research G4, checked 17 Oct 2026).
 *
 * Who runs it: a developer, by hand, when the JSON changes (a change before S1-E10-13b is a new
 * migration): `npx tsx scripts/build-safety-contacts-migration.ts <output .sql path>`. Its unit
 * test (build-safety-contacts-migration.test.ts) proves the SQL it writes matches the JSON.
 * Why a builder: numbers are safety-critical and are never typed from memory (the story's legal
 * note); every row carries its source link, its check date and the research's confidence.
 * What it leaves out: the "unconfirmed" lists (watch items for the monthly check, S1-E10-13b) and
 * any line the research marks adult-focused (decided 23 Oct 2026, Q9a: no ARPS line for Romania).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

/** One contact as the JSON holds it. */
interface ContactEntry {
  label: string;
  number: string | null;
  url: string | null;
  hours?: string;
  confidence?: string;
  note?: string;
}

/** The kinds the table stores, in the order the block shows them. */
export const contactKinds = [
  'emergency',
  'child_helpline',
  'csam_hotline',
  'crisis_youth',
  'police_online_child',
  'regulator',
] as const;

/** One row of the migration. */
export interface ContactRow {
  countryCode: string;
  kind: (typeof contactKinds)[number];
  position: number;
  label: string;
  phoneNumber: string | null;
  link: string | null;
  openingHours: string | null;
  note: string | null;
  confidence: string;
  lastCheckedOn: string;
}

/**
 * Whether a line is for adults only, which the block never shows (decided 23 Oct 2026, Q9a).
 *
 * @param entry - the contact
 * @returns true for a label the research marks "adult-focused"
 */
function isAdultOnly(entry: ContactEntry): boolean {
  return /adult-focused/i.test(entry.label);
}

/**
 * Turns the JSON into rows.
 *
 * @param json - the parsed content/safety-contacts.json
 * @returns the rows, country by country, kind by kind, in the file's order
 */
export function rowsFromJson(json: Record<string, Record<string, unknown>>): ContactRow[] {
  const rows: ContactRow[] = [];
  for (const [countryCode, country] of Object.entries(json)) {
    const checked = typeof country.checked === 'string' ? country.checked : '';
    for (const kind of contactKinds) {
      const entries = Array.isArray(country[kind]) ? (country[kind] as ContactEntry[]) : [];
      entries
        .filter((entry) => !isAdultOnly(entry))
        .forEach((entry, index) => {
          rows.push({
            countryCode,
            kind,
            position: index + 1,
            label: entry.label,
            phoneNumber: entry.number ?? null,
            link: entry.url ?? null,
            openingHours: entry.hours ?? null,
            note: entry.note ?? null,
            confidence: entry.confidence ?? 'Unknown',
            lastCheckedOn: checked,
          });
        });
    }
  }
  return rows;
}

/**
 * Quotes a value for SQL.
 *
 * @param value - the text, or null
 * @returns 'text' with single quotes doubled, or NULL
 */
export function sqlText(value: string | null): string {
  return value === null ? 'null' : `'${value.replaceAll("'", "''")}'`;
}

/**
 * Writes the whole migration.
 *
 * @param rows - from rowsFromJson()
 * @returns the SQL text
 */
export function migrationFromRows(rows: ContactRow[]): string {
  const values = rows.map(
    (row) =>
      `  (${sqlText(row.countryCode)}, ${sqlText(row.kind)}, ${row.position}, ${sqlText(row.label)}, ` +
      `${sqlText(row.phoneNumber)}, ${sqlText(row.link)}, ${sqlText(row.openingHours)}, ${sqlText(row.note)}, ` +
      `${sqlText(row.confidence)}, ${sqlText(row.lastCheckedOn)})`,
  );
  return [
    '-- Safety contacts by country, seeded from content/safety-contacts.json (story S1-E10-13a;',
    '-- research G4, checked 17 Oct 2026). GENERATED by scripts/build-safety-contacts-migration.ts:',
    '-- never edit by hand, never type a number from memory. A change before the editing screen',
    '-- (S1-E10-13b) is a new migration from the changed JSON.',
    '',
    '-- A new generation replaces the previous research rows, so a changed JSON is one migration.',
    "delete from public.safety_contacts where checked_by = 'research G4';",
    '',
    'insert into public.safety_contacts (country_code, kind, position, label, phone_number, link,',
    '  opening_hours, note, confidence, last_checked_on) values',
    `${values.join(',\n')};`,
    '',
  ].join('\n');
}

// Run as a script: read the JSON, write the migration to the path given.
if (
  process.argv[1] !== undefined &&
  process.argv[1].endsWith('build-safety-contacts-migration.ts')
) {
  const outputPath = process.argv[2];
  if (outputPath === undefined) {
    console.error('Usage: npx tsx scripts/build-safety-contacts-migration.ts <output .sql path>');
    process.exit(1);
  }
  const json = JSON.parse(readFileSync(resolve('content/safety-contacts.json'), 'utf8')) as Record<
    string,
    Record<string, unknown>
  >;
  writeFileSync(outputPath, migrationFromRows(rowsFromJson(json)));
  console.log(`Wrote ${rowsFromJson(json).length} contacts to ${outputPath}`);
}
